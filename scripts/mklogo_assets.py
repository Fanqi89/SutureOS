#!/usr/bin/env python3
"""Convert the SutureOS logo PNG ladder into C bitmaps for the Rust GUI shell.

Runtime rule (logo/README.md): the kernel never decodes PNG. `logo/` is the
source asset folder; this script emits `kernel/gui/logo_assets.c/.h`, which the
normal build compiles into the kernel.

- 24x24 / 48x48: taken **directly** from the provided size ladder (no resample).
- 768x768: the 1536 master decimated 2:1 (exact pixel selection, no interpolation,
  no colour change) so the full-screen shutdown animation can be drawn on the
  1024x768 framebuffer without a second resample at runtime.

Pixel format: 0x00RRGGBB (the same u32 layout the GUI surface uses).
"""
import os

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOGO = os.path.join(ROOT, 'logo')
OUT_C = os.path.join(ROOT, 'kernel', 'gui', 'logo_assets.c')
OUT_H = os.path.join(ROOT, 'kernel', 'gui', 'logo_assets.h')


def load(name):
    # keep RGBA: the ladder has a transparent background and the C blitter
    # alpha-blends, so alpha must not be thrown away here (convert('RGB') here
    # was what left a white square behind every logo).
    return Image.open(os.path.join(LOGO, name)).convert('RGBA')


def pack(img, w, h):
    """0xAARRGGBB: the PNG ladder has a transparent background, so the alpha
    channel has to survive into the C array; the shell blitter alpha-blends."""
    px = list(img.convert('RGBA').getdata())
    assert len(px) == w * h, (len(px), w, h)
    out = []
    for r, g, b, a in px:
        out.append((a << 24) | (r << 16) | (g << 8) | b)
    return out


def emit_array(fh, name, data, w, h):
    fh.write('/* %dx%d */\n' % (w, h))
    fh.write('const uint32_t %s[%d] = {\n' % (name, len(data)))
    for i in range(0, len(data), 12):
        fh.write('    ' + ', '.join('0x%06x' % v for v in data[i:i + 12]) + ',\n')
    fh.write('};\n\n')


def main():
    l24 = load('SutureOS_logo_24.png')
    l48 = load('SutureOS_logo_48.png')
    l1536 = load('SutureOS_logo_1536.png')
    assert l24.size == (24, 24) and l48.size == (48, 48) and l1536.size == (1536, 1536)
    # exact 2:1 decimation of the master (pick every second pixel; no blend)
    l768 = l1536.resize((768, 768), Image.NEAREST)
    d24 = pack(l24, 24, 24)
    d48 = pack(l48, 48, 48)
    d768 = pack(l768, 768, 768)

    hdr = '''/* SutureOS logo bitmaps - generated by scripts/mklogo_assets.py, do not edit.
 *
 * Original artwork (see logo/README.md). The kernel never reads PNG: these
 * arrays are compiled into .rodata and used by the Rust GUI shell for the
 * start-button icon, the start-menu header and the shutdown animation.
 */
#ifndef SUTUREOS_LOGO_ASSETS_H
#define SUTUREOS_LOGO_ASSETS_H

#include <stdint.h>

#define LOGO_SMALL_SIZE 24
#define LOGO_MENU_SIZE  48
#define LOGO_FULL_SIZE  768

extern const uint32_t g_logo24[LOGO_SMALL_SIZE * LOGO_SMALL_SIZE];
extern const uint32_t g_logo48[LOGO_MENU_SIZE * LOGO_MENU_SIZE];
extern const uint32_t g_logo768[LOGO_FULL_SIZE * LOGO_FULL_SIZE];

#endif /* SUTUREOS_LOGO_ASSETS_H */
'''
    src = '''/* SutureOS logo bitmaps - generated by scripts/mklogo_assets.py, do not edit. */
#include "logo_assets.h"

'''
    with open(OUT_H, 'w', encoding='utf-8', newline='') as fh:
        fh.write(hdr)
    with open(OUT_C, 'w', encoding='utf-8', newline='') as fh:
        fh.write(src)
        emit_array(fh, 'g_logo24', d24, 24, 24)
        emit_array(fh, 'g_logo48', d48, 48, 48)
        emit_array(fh, 'g_logo768', d768, 768, 768)
    print('wrote', OUT_H)
    print('wrote', OUT_C, '(%d bytes)' % os.path.getsize(OUT_C))


if __name__ == '__main__':
    main()
